"""Convert the site's logo PNG to a C RGB565 array, composited on the cream header colour."""
import sys
from PIL import Image
src, size, out = sys.argv[1], int(sys.argv[2]), sys.argv[3]
im = Image.open(src).convert("RGBA").resize((size, size), Image.LANCZOS)
bg = Image.new("RGBA", im.size, (247, 241, 227, 255))
im = Image.alpha_composite(bg, im).convert("RGB")
vals = []
for r, g, b in im.getdata():
    v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
    vals.append(f"0x{v:04X}")
with open(out, "w") as f:
    f.write(f"// Generated by tools/logo_to_c.py from img/logo-192.png\n#pragma once\n#include <stdint.h>\n")
    f.write(f"#define LOGO_W {size}\n#define LOGO_H {size}\nstatic const uint16_t LOGO[{size*size}] = {{\n")
    for i in range(0, len(vals), 16):
        f.write("  " + ",".join(vals[i:i+16]) + ",\n")
    f.write("};\n")
